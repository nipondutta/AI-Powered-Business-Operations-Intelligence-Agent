import re
from sqlalchemy import create_engine, text
from app.config import settings
from app.llm import generate

BLOCKED = re.compile(
    r"\b(INSERT|UPDATE|DELETE|DROP|ALTER|CREATE|ATTACH|"
    r"DETACH|PRAGMA|REPLACE|TRUNCATE|GRANT|REVOKE|VACUUM)\b",
    re.IGNORECASE
)

ALLOWED_TABLES = {"customers", "products", "orders", "tickets"}

def validate_readonly_sql(sql: str) -> str:
    cleaned = sql.strip()

    # Remove Markdown code fences
    cleaned = re.sub(
        r"^```(?:sql)?\s*|\s*```$",
        "",
        cleaned,
        flags=re.IGNORECASE
    ).strip()

    # Remove trailing semicolon
    cleaned = cleaned.rstrip(";").strip()

    if not cleaned:
        raise ValueError("SQL query cannot be empty.")

    if ";" in cleaned:
        raise ValueError("Multiple SQL statements are not permitted.")

    # Check SELECT statement
    if not re.match(r"^SELECT\b", cleaned, re.IGNORECASE):
        raise ValueError(
            "Only SELECT queries are permitted."
        )

    # Check dangerous SQL operations
    if BLOCKED.search(cleaned):
        raise ValueError(
            "Write and administrative SQL operations are blocked."
        )

    # Extract referenced tables
    mentioned = set(
        re.findall(
            r"\b(?:FROM|JOIN)\s+([a-zA-Z_][a-zA-Z0-9_]*)",
            cleaned,
            re.IGNORECASE
        )
    )

    if not mentioned:
        raise ValueError("Query must reference an approved business table.")

    if not mentioned.issubset(ALLOWED_TABLES):
        raise ValueError(
            f"Unauthorized tables referenced: {mentioned - ALLOWED_TABLES}"
        )

    if not re.search(r"\bLIMIT\s+\d+(?:\s+OFFSET\s+\d+)?\s*$", cleaned, re.IGNORECASE):
        cleaned += " LIMIT 200"

    return cleaned

def execute_readonly(sql: str):
    safe = validate_readonly_sql(sql)
    if settings.database_url.startswith("sqlite"):
        db_path = settings.database_url.replace("sqlite:///", "", 1)
        db_engine = create_engine(f"sqlite:///file:{db_path}?mode=ro&uri=true")
    else:
        db_engine = create_engine(settings.database_url, pool_pre_ping=True)
    try:
        with db_engine.connect() as conn:
            return [dict(row._mapping) for row in conn.execute(text(safe))]
    finally:
        db_engine.dispose()

def answer_analytics(question: str):

    q = question.lower()

    # Handle total revenue using trusted SQL
    if (
        "total revenue" in q
        or "revenue generated" in q
        or "overall revenue" in q
    ):
        sql = """
        SELECT
            COALESCE(
                SUM(
                    quantity * unit_price *
                    (1 - COALESCE(discount, 0))
                ),
                0
            ) AS total_revenue
        FROM orders
        """

    else:
        schema = """
        customers(customer_id, name, city, signup_date, segment);
        products(product_id, product_name, category, unit_price, cost_price);
        orders(order_id, customer_id, product_id, order_date,
               quantity, unit_price, discount, status);
        tickets(ticket_id, customer_id, created_at, category,
                priority, sentiment, status, message).

        Revenue formula:
        SUM(quantity * unit_price * (1 - COALESCE(discount, 0))).

        Important:
        - Use only the supplied columns.
        - Never invent columns.
        - Do not use cost_price to calculate revenue.
        - Return exactly one SELECT query.
        - Do not include Markdown or explanations.
        """

        raw = generate(
            f"Generate SQL for this question: {question}\nSchema: {schema}",
            "You are a read-only SQLite SQL generator. Return SQL only."
        )

        if not raw:
            return {
                "answer": "Ollama is unavailable.",
                "sql": None,
                "data": []
            }

        sql = raw.strip()
        sql = re.sub(
            r"^```(?:sql)?\s*|\s*```$",
            "",
            sql,
            flags=re.IGNORECASE
        ).strip()

    try:
        safe = validate_readonly_sql(sql)
        rows = execute_readonly(safe)

    except Exception as exc:
        return {
            "answer": f"SQL execution failed: {exc}",
            "sql": sql,
            "data": []
        }

    if not rows:
        answer = "No business data was found."

    elif "total_revenue" in rows[0]:
        revenue = rows[0]["total_revenue"]
        answer = f"Total revenue generated by the business is {revenue:,.2f}."

    else:
        summary = generate(
            f"Question: {question}\nResults: {rows[:100]}\n"
            "Explain only what these results support. Do not invent figures.",
            "You are a precise business analyst."
        )

        answer = summary or f"Query returned {len(rows)} rows."

    return {
        "answer": answer,
        "sql": safe,
        "data": rows
    }